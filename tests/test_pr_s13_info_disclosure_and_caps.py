def test_webhook_aliases_match_original_routes(monkeypatch, tmp_path):
    main = _load_api(monkeypatch, tmp_path)
    client = TestClient(main.app)

    bad_sig_headers = {
        "webhook-id": "msg_bad",
        "webhook-timestamp": str(int(time.time())),
        "webhook-signature": "v1,bad",
        "Content-Type": "application/json",
    }
    body = json.dumps({"metadata": {"trigger_id": "ct_missing"}}).encode()

    original = client.post("/composio-events", content=body, headers=bad_sig_headers)
    alias = client.post("/webhooks/composio-events", content=body, headers=bad_sig_headers)
    assert original.status_code == 401, original.text
    assert alias.status_code == 401, alias.text
    assert original.json() == alias.json()

    # Valid signatures should behave the same too (404 in both paths with no worker match).
    sig_headers = _signed_headers(body, "whsec-test")
    original_valid = client.post("/composio-events", content=body, headers=sig_headers)
    alias_valid = client.post("/webhooks/composio-events", content=body, headers=sig_headers)
    assert original_valid.status_code == 404, original_valid.text
    assert alias_valid.status_code == 404, alias_valid.text
    assert original_valid.json() == alias_valid.json()

    callback_qs = "?connection_id=unknown_conn&status=success"
    cb_original = client.get(f"/connections/callback{callback_qs}", follow_redirects=False)
    cb_alias = client.get(f"/webhooks/oauth-callback{callback_qs}", follow_redirects=False)
    assert cb_original.status_code == cb_alias.status_code
    assert cb_original.headers.get("location") == cb_alias.headers.get("location")
