def _load_api(
    monkeypatch,
    tmp_path,
    *,
    draft_rate_hour: int = 20,
    run_create_rate_minute: int = 10,
):
    workers_dir = tmp_path / "workers"
    workers_dir.mkdir()
    artifacts_dir = tmp_path / "artifacts"
    artifacts_dir.mkdir()
    db_path = tmp_path / "floom.db"

    monkeypatch.setenv("FLOOM_DB", str(db_path))
    monkeypatch.setenv("FLOOM_WORKERS_DIR", str(workers_dir))
    monkeypatch.setenv("FLOOM_ARTIFACTS_DIR", str(artifacts_dir))
    monkeypatch.setenv("FLOOM_SECRET", _AUTH_HEADER["x-floom-secret"])
    monkeypatch.setenv("OPENAI_API_KEY", "sk-test")
    monkeypatch.setenv("E2B_API_KEY", "e2b-test")
    monkeypatch.setenv("COMPOSIO_API_KEY", "cmp-test")
    monkeypatch.setenv("COMPOSIO_WEBHOOK_SIGNING_KEY", "whsec-test")
    monkeypatch.setenv("WORKERS_FRONTEND_URL", "https://workers.floom.dev")
    monkeypatch.setenv("WORKEROS_DRAFT_RATE_HOUR", str(draft_rate_hour))
    monkeypatch.setenv("WORKEROS_RUN_CREATE_RATE_LIMIT", str(run_create_rate_minute))
    monkeypatch.setenv("WORKEROS_RUN_CREATE_RATE_WINDOW_SECONDS", "60")

    reset_prefixes = ("auth.", "db.")
    reset_exact = {
        "main",
        "auth",
        "db",
        "files",
        "models",
        "worker_registry",
        "run_service",
        "composio_client",
        "runner_utils",
        "scheduler",
    }
    for name in list(sys.modules):
        if name in reset_exact or name.startswith(reset_prefixes):
            sys.modules.pop(name, None)

    # Avoid startup scheduler side-effects in tests.
    sys.modules["scheduler"] = types.SimpleNamespace(
        start_scheduler=lambda: None,
        stop_scheduler=lambda: None,
    )
    main = importlib.import_module("main")
    main.get_auth_provider.cache_clear()
    return main


def _valid_draft_payload(name: str = "s13-draft-worker") -> Dict[str, Any]:
    worker_yml = f"""
schema_version: "0.3"
name: "{name}"
title: "S13 Draft Worker"
description: "Worker generated by tests."
version: "0.1.0"
targets: ["generic"]
exec:
  entry: "SKILL.md"
  runtime: "skill"
  runner: "e2b"
trigger:
  type: "manual"
"""
    return {
        "worker_yml": worker_yml.strip(),
        "skill_md": "You are a test worker.",
        "suggested_name": name,
        "suggested_title": "S13 Draft Worker",
        "requirements": [],
        "required_connections": [],
        "required_secrets": [],
        "inputs": [{"name": "topic", "type": "string", "label": "Topic", "required": True}],
        "outputs": [{"name": "summary", "type": "markdown", "label": "Summary"}],
        "files": [
            {"path": "worker.yml", "content": worker_yml.strip()},
            {"path": "SKILL.md", "content": "You are a test worker."},
        ],
    }


def _worker_yml(
    name: str,
    *,
    mode: str = "pure-script",
    trigger_type: str = "manual",
) -> str:
    entry = "run.py" if mode == "pure-script" else "SKILL.md"
    runtime = "python311" if mode == "pure-script" else "skill"
    if trigger_type == "webhook":
        trigger_block = """
trigger:
  type: "webhook"
  webhook:
    secret: true
""".strip()
    else:
        trigger_block = f"""
trigger:
  type: "{trigger_type}"
""".strip()
    return f"""
schema_version: "0.3"
name: {name}
title: "S13 Worker {name}"
description: "Worker generated by tests."
version: "0.1.0"
targets: ["generic"]
exec:
  entry: "{entry}"
  runtime: "{runtime}"
  runner: "e2b"
  command: "python run.py"
  inputs: []
  outputs: []
{trigger_block}
""".strip()


def _symlink_bundle(name: str) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        zf.writestr("worker.yml", _worker_yml(name))
        info = zipfile.ZipInfo("linked")
        info.external_attr = (0o120777 << 16)
        zf.writestr(info, "target")
    return buf.getvalue()


def _signed_headers(body: bytes, signing_key: str) -> Dict[str, str]:
    msg_id = "msg_s13"
    ts = str(int(time.time()))
    payload = f"{msg_id}.{ts}.{body.decode('utf-8')}".encode()
    digest = hmac.new(signing_key.encode(), payload, hashlib.sha256).digest()
    sig = "v1," + base64.b64encode(digest).decode()
    return {
        "webhook-id": msg_id,
        "webhook-timestamp": ts,
        "webhook-signature": sig,
        "Content-Type": "application/json",
    }


def _insert_minimal_worker(main: Any, worker_id: str, *, secrets: list[str] | None = None) -> None:
    now = main.now_iso()
    skill_version_id = f"skill_{worker_id}"
    manifest = {
        "id": worker_id,
        "name": worker_id,
        "description": "audit test worker",
        "version": "0.1.0",
        "runtime": {"type": "python311", "entrypoint": "run.py", "runner": "e2b"},
        "secrets": secrets or [],
        "inputs": [],
        "outputs": [],
        "trigger": {"type": "manual"},
    }
    with main.get_db() as conn:
        conn.execute(
            """
            INSERT INTO skill_versions (id, name, version, manifest_json, bundle_path, created_at)
            VALUES (?, ?, '0.1.0', ?, ?, ?)
            """,
            (skill_version_id, worker_id, json.dumps(manifest), f"workers/{worker_id}", now),
        )
        conn.execute(
            """
            INSERT INTO workers (id, skill_version_id, name, trigger_type, created_at, owner_id)
            VALUES (?, ?, ?, 'manual', ?, 'federico')
            """,
            (worker_id, skill_version_id, worker_id, now),
        )


